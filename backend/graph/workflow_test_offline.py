def mock_synthesis_node(state):
    """
    Offline synthesis agent.
    """

    pieces = []

    if state.get("faculty_evidence"):
        pieces.append("Faculty evidence used.")

    if state.get("research_evidence"):
        pieces.append("Current research used.")

    if state.get("emergency_response"):
        pieces.append("Emergency response used.")

    state["proposed_answer"] = " ".join(pieces)

    return state


