def mock_router_node(state):
    """
    Offline replacement for the real router agent.

    This allows us to test LangGraph without calling OpenAI.
    """

    question = state["question"].lower()

    # Emergency question
    if "want to die" in question or "suicide" in question:
        state["route"] = {
            "faculty_rag": False,
            "current_research": False,
            "emergency": True,
            "synthesis": True,
            "verification": True,
            "intent": "Emergency safety response",
            "reason": "Emergency language detected.",
            "confidence": "high",
            "priority": "Immediate",
        }

    # Current/latest question
    elif "latest" in question or "2026" in question:
        state["route"] = {
            "faculty_rag": False,
            "current_research": True,
            "emergency": False,
            "synthesis": True,
            "verification": True,
            "intent": "Current medical information",
            "reason": "Question requires current external research.",
            "confidence": "high",
            "priority": "Normal",
        }

    # Faculty knowledge question
    else:
        state["route"] = {
            "faculty_rag": True,
            "current_research": False,
            "emergency": False,
            "synthesis": True,
            "verification": True,
            "intent": "Faculty knowledge question",
            "reason": "Question can be answered using faculty material.",
            "confidence": "high",
            "priority": "Normal",
        }

    return state


